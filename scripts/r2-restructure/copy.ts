// Copies every pre-restructure image of the given stores into the new layout
// (<store>/images/<stem>.<ext>) in the R2 bucket `cigarro-assets`, then writes
// convex/lib/storageKeyMap.ts, which restructureStorageKeys-v1 reads.
//
// Copy only, never move or delete. Every copy goes through the admin endpoint
// POST /api/images/upload?action=copy, which is create-only: an existing target
// with the same bytes is "exists" (fine on a re-run), with different bytes it is
// "conflict" and nothing is written. Failures leave the map without that key, so
// its old URL keeps working.
//
// Bucket: cigarro-assets (R2). The origin decides which deployment writes to it:
// the production admin host by default.
//
// Usage (run from the repo root):
//   $env:IMPORT_TOKEN = "<cigarro_token of a super/store admin of each store>"
//   npx tsx scripts/r2-restructure/copy.ts --dry-run
//   npx tsx scripts/r2-restructure/copy.ts --origin https://admin.cigarro.in --stores oldsmokeshop,smokeshop
//
// Re-run as often as needed: keys already copied are skipped, and the planner keeps
// every name it already assigned.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { STORAGE_KEY_MAP } from "../../convex/lib/storageKeyMap";
import { legacyOwner, planNewKeys, type KeyMap } from "../../convex/lib/storageKeys";

const LEGACY_SLUG = "oldsmokeshop";
const CONCURRENCY = 4;
const here = path.dirname(fileURLToPath(import.meta.url));
const mapPath = path.join(here, "..", "..", "convex", "lib", "storageKeyMap.ts");
const logDir = path.join(here, "logs");

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const origin = (arg("--origin") ?? "https://admin.cigarro.in").replace(/\/$/, "");
const stores = (arg("--stores") ?? "oldsmokeshop,smokeshop").split(",").map((s) => s.trim()).filter(Boolean);
const dryRun = process.argv.includes("--dry-run");
const token = process.env.IMPORT_TOKEN ?? "";
if (!token) {
  console.error("IMPORT_TOKEN is not set (a cigarro_token for each store listed in --stores).");
  process.exit(1);
}

fs.mkdirSync(logDir, { recursive: true });
const stamp = new Date().toISOString().replace(/[:.]/g, "-");
const logFile = path.join(logDir, `copy-${stamp}.log`);
function log(line: string) {
  console.log(line);
  fs.appendFileSync(logFile, `${line}\n`);
}

async function listLegacy(store: string): Promise<string[]> {
  const keys: string[] = [];
  let cursor: string | undefined;
  do {
    const u = new URL("/api/images/upload", origin);
    u.searchParams.set("legacy", "1");
    if (cursor) u.searchParams.set("cursor", cursor);
    const res = await fetch(u, { headers: { Authorization: `Bearer ${token}`, "X-Store": store } });
    const body = (await res.json().catch(() => ({}))) as { images?: { key: string }[]; cursor?: string; error?: string };
    if (!res.ok) throw new Error(`list ${store}: HTTP ${res.status} ${body.error ?? ""}`);
    for (const img of body.images ?? []) keys.push(img.key);
    cursor = body.cursor;
  } while (cursor);
  return keys;
}

async function copyOne(from: string, to: string): Promise<{ status: string; error?: string }> {
  const owner = legacyOwner(from, LEGACY_SLUG) ?? LEGACY_SLUG;
  let last = { status: "error", error: "no attempt" };
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(`${origin}/api/images/upload?action=copy`, {
        method: "POST",
        headers: { Authorization: `Bearer ${token}`, "X-Store": owner, "Content-Type": "application/json" },
        body: JSON.stringify({ from, to }),
      });
      const body = (await res.json().catch(() => ({}))) as { status?: string; error?: string };
      last = { status: body.status ?? `http-${res.status}`, error: body.error };
      if (res.ok || body.status === "conflict") return last;
    } catch (err) {
      last = { status: "error", error: err instanceof Error ? err.message : String(err) };
    }
    await new Promise((r) => setTimeout(r, 500 * attempt));
  }
  return last;
}

function writeMap(map: KeyMap) {
  const entries = Object.keys(map)
    .sort()
    .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`)
    .join("\n");
  const body = [
    "// Generated by scripts/r2-restructure/copy.ts. Do not edit by hand.",
    "// Pre-restructure R2 key → new key (<store>/images/…), only for keys whose copy",
    "// was verified (same bytes at the target). Empty until the copy script has run:",
    "// restructureStorageKeys-v1 refuses to run on an empty map.",
    "export const STORAGE_KEY_MAP: Record<string, string> = {",
    entries,
    "};",
    "",
  ].join("\n");
  fs.writeFileSync(mapPath, body);
}

async function main() {
  const listed = new Set<string>();
  for (const store of stores) {
    const keys = await listLegacy(store);
    log(`listed ${keys.length} pre-restructure images for ${store}`);
    keys.forEach((k) => listed.add(k));
  }

  const plan = planNewKeys([...listed], LEGACY_SLUG, STORAGE_KEY_MAP);
  const todo = Object.keys(plan).filter((from) => !(from in STORAGE_KEY_MAP));
  log(`${listed.size} images listed; ${Object.keys(STORAGE_KEY_MAP).length} already in the map; ${todo.length} to copy`);
  for (const from of todo) log(`plan  ${from} -> ${plan[from]}`);
  if (dryRun) {
    log("dry run: nothing copied, map not written");
    return 0;
  }

  const done: KeyMap = {};
  const failed: string[] = [];
  let next = 0;
  const worker = async () => {
    while (next < todo.length) {
      const from = todo[next++];
      const to = plan[from];
      const r = await copyOne(from, to);
      if (r.status === "copied" || r.status === "exists") {
        done[from] = to;
        log(`${r.status.padEnd(7)} ${from} -> ${to}`);
      } else {
        failed.push(from);
        log(`FAILED  ${from} -> ${to}: ${r.status} ${r.error ?? ""}`);
      }
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  // Keep the map to verified copies only. A missing key simply keeps its old URL.
  const final: KeyMap = { ...STORAGE_KEY_MAP, ...done };
  writeMap(final);
  log(`map written: ${Object.keys(final).length} keys in ${path.relative(process.cwd(), mapPath)}`);
  log(failed.length ? `${failed.length} failed; re-run before the migration` : "all copies verified");
  return failed.length ? 1 : 0;
}

main()
  .then((code) => process.exit(code))
  .catch((err) => {
    log(`aborted: ${err instanceof Error ? err.message : String(err)}`);
    process.exit(1);
  });
